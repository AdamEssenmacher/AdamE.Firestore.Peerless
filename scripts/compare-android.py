#!/usr/bin/env python3
"""Side-by-side comparison of Android benchmark runs (any mix of peered / peerless-direct / peerless-bytes).

Usage: scripts/compare-android.py OUT.md RUN_DIR [RUN_DIR ...]
Runs of the same mode are pooled: each table cell is the median over every matching callback in every run of that mode.
"""
import csv, re, statistics, sys
from collections import defaultdict
from pathlib import Path

out = Path(sys.argv[1])
runs = [Path(arg) for arg in sys.argv[2:]]
MODES = ["peered", "peerless-direct", "peerless-bytes"]


def mode_of(run):
    return next(p.name[: -len("-samples.csv")] for p in run.glob("*-samples.csv"))


samples = defaultdict(list)  # (mode, phase, size, kind) -> rows
settled = defaultdict(list)  # (mode, phase, size, point) -> gref
art = defaultdict(list)      # (mode, phase, size, point) -> ART global refs
notes = []
for run in runs:
    mode = mode_of(run)
    run_settled = list(csv.DictReader(open(run / f"{mode}-settled.csv")))
    for row in run_settled:
        settled[(mode, row["phase"], int(row["size"]), row["point"])].append(int(row["gref"]))

    # Peak over the last settle point before the sample (recorded by newer runs, reconstructed for older ones).
    order = defaultdict(list)
    for row in run_settled:
        point = row["point"]
        key = -1 if point == "before-listen" else 0 if point == "after-initial" else (
            int(point.rsplit("-", 1)[1]) if point.startswith("after-update-") else None)
        if key is not None:
            order[(row["phase"], int(row["size"]))].append((key, int(row["gref"])))
    for row in csv.DictReader(open(run / f"{mode}-samples.csv")):
        if row["phase"] not in ("query", "document"):
            continue
        if not row.get("gref_peak_over_settled") and row.get("gref_peak"):
            seq = int(row["seq"])
            earlier = [g for k, g in order[(row["phase"], int(row["size"]))] if k < seq or (seq == 0 and k == -1)]
            if earlier:
                row["gref_peak_over_settled"] = str(float(row["gref_peak"]) - earlier[-1])
        # Updates that come straight after a settle point are reported on their own, in every mode: forced GCs at the
        # settle point make some of the following peered callbacks run GC storms (see results/android-peered).
        kind = row["kind"]
        if kind == "update" and any(k == int(row["seq"]) - 1 for k, _ in order[(row["phase"], int(row["size"]))]):
            kind = "update, after a settle"
        samples[(mode, row["phase"], int(row["size"]), kind)].append(row)
    summary = (run / "summary.md").read_text() if (run / "summary.md").exists() else ""
    summary = summary.split("## ART's JNI tables", 1)[1] if "## ART's JNI tables" in summary else ""
    for m in re.finditer(r"^\| (\w+) \| (\d+) \| ([\w-]+) \| (\d+) \| (\d+) \|", summary, re.M):
        if m.group(1) in ("query", "document"):
            art[(mode, m.group(1), int(m.group(2)), m.group(3))].append(int(m.group(4)))
    host = (run / "host.txt").read_text() if (run / "host.txt").exists() else ""
    loads = re.findall(r"load averages?: ([\d.]+)", host)
    verify = re.search(r"^verify: (.*)$", (run / f"{mode}-run.txt").read_text(), re.M)
    outcome = re.search(r"^outcome: (.*)$", (run / f"{mode}-run.txt").read_text(), re.M)
    notes.append(f"| {run.name} | {mode} | {outcome.group(1) if outcome else '?'} | "
                 f"{' → '.join(loads) if loads else '?'} | {verify.group(1) if verify else '?'} |")


def med(rows, key, scale=1.0):
    values = [float(r[key]) for r in rows if r.get(key)]
    return statistics.median(values) / scale if values else None


def cell(value, digits=1):
    return "–" if value is None else f"{value:,.{digits}f}"


present = [m for m in MODES if any(k[0] == m for k in samples)]
cases = sorted({k[1:] for k in samples}, key=lambda c: (c[0] != "query", c[1], c[2]))

lines = ["# Android: peered vs Peerless (generated)", "",
         f"Generated by `scripts/compare-android.py` from {len(runs)} runs. Every cell is a median over all callbacks of "
         "that case in all runs of that mode. Wall and CPU span the whole path each mode has: peered from entry into the "
         ".NET listener; Peerless from entry into the Java listener (so it includes encoding). Both end with the "
         "snapshot fully converted into the same .NET value model.", "",
         "## Runs", "", "| run | mode | outcome | host load (1-min) before → after | peered = peerless check |",
         "|---|---|---|---|---|", *notes, ""]


def table(title, key, scale, digits, explain):
    lines.extend([f"## {title}", "", explain, "",
                  "| docs | kind | " + " | ".join(present) + (" | peered ÷ direct |" if "peered" in present and "peerless-direct" in present else " |"),
                  "|---:|---|" + "---:|" * len(present) + ("---:|" if "peered" in present and "peerless-direct" in present else "")])
    for phase, size, kind in cases:
        values = {m: med(samples.get((m, phase, size, kind), []), key, scale) for m in present}
        label = f"{size} (doc)" if phase == "document" else str(size)
        ratio = ""
        if "peered" in values and "peerless-direct" in values:
            p, d = values["peered"], values["peerless-direct"]
            ratio = f" {p / d:,.0f}× |" if p and d else " – |"
        lines.append(f"| {label} | {kind} | " + " | ".join(cell(values[m], digits) for m in present) + " |" + ratio)
    lines.append("")


table("Wall time per snapshot (ms)", "wall_us", 1000, 2, "Callback start to fully converted.")
table("Main-thread CPU per snapshot (ms)", "thread_cpu_us", 1000, 2,
      "Thread CPU time on the callback (main) thread over the same span; for Peerless this includes Java encoding.")
table("Managed allocation per snapshot (KB)", "alloc_bytes", 1024, 0,
      ".NET allocations on the callback thread. Java-side allocations (getData() maps, the frame buffer) aren't counted in either mode.")
table("JNI global references at peak during a snapshot (absolute)", "gref_peak", 1, 0,
      "The highest .NET-side count seen during the callback (sampled per document in peered mode): what an app sees, "
      "since an app never forces the settles this benchmark does. The .NET counter leaves out ~435 java.lang.Class "
      "references Java.Interop caches.")
table("JNI global references at peak during a snapshot, over the last settle point", "gref_peak_over_settled", 1, 0,
      "The peak minus the count at the last settle point (forced .NET and Java GC). That removes only references that "
      "survive a full GC; references earlier callbacks left for the GC since the settle are still included, so the "
      "figure grows with the callbacks since it. Cadence: a settle before listening, after the initial snapshot and "
      "after every 5th update (every 12th in the single-document phase).")
table("GCs during a snapshot", "gen0", 1, 0, "Collections of any generation that started inside the callback.")

lines += ["## Settled JNI global references (after forced .NET + Java GC)", "",
          "ART's own global reference table at the settle points (median across runs).", "",
          "| docs | point | " + " | ".join(present) + " |", "|---:|---|" + "---:|" * len(present)]
for phase, size in sorted({(k[1], k[2]) for k in art}, key=lambda c: (c[0] != "query", c[1])):
    for point in ("before-listen", "after-initial", "after-update-20", "after-remove"):
        if not any(art.get((m, phase, size, point)) for m in present):
            continue
        values = [art.get((m, phase, size, point)) for m in present]
        lines.append(f"| {size}{' (doc)' if phase == 'document' else ''} | {point} | "
                     + " | ".join(f"{statistics.median(v):,.0f}" if v else "–" for v in values) + " |")
lines.append("")

if any(m.startswith("peerless") for m in present):
    lines += ["## Peerless: where the time goes", "",
              "Medians. *Encode* is the Java writer alone. *Java→.NET* is Java callback entry to .NET entry (encode, "
              "copy into the delivery buffer, JNI call). *.NET* is .NET entry to fully decoded.", "",
              "| mode | docs | kind | frame KB | encode ms | encode CPU ms | Java→.NET ms | .NET ms | end-to-end ms |",
              "|---|---:|---|---:|---:|---:|---:|---:|---:|"]
    for m in [m for m in present if m.startswith("peerless")]:
        for phase, size, kind in cases:
            rows = samples.get((m, phase, size, kind), [])
            if not rows:
                continue
            lines.append(f"| {m} | {size}{' (doc)' if phase == 'document' else ''} | {kind} | "
                         f"{cell(med(rows, 'frame_bytes', 1024))} | {cell(med(rows, 'java_encode_us', 1000), 2)} | "
                         f"{cell(med(rows, 'java_encode_cpu_us', 1000), 2)} | {cell(med(rows, 'java_to_dotnet_us', 1000), 2)} | "
                         f"{cell(med(rows, 'dotnet_us', 1000), 2)} | {cell(med(rows, 'wall_us', 1000), 2)} |")
    lines.append("")

out.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
