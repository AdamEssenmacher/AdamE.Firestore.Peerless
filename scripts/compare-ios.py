#!/usr/bin/env python3
"""Side-by-side comparison of iOS benchmark runs (peered / peerless).

Usage: scripts/compare-ios.py OUT.md RUN_DIR [RUN_DIR ...]
Runs of the same mode are pooled: each table cell is the median over every matching callback in every run of that mode.
"""
import csv, re, statistics, sys
from collections import defaultdict
from pathlib import Path

out = Path(sys.argv[1])
runs = [Path(arg) for arg in sys.argv[2:]]
MODES = ["peered", "peerless"]


def mode_of(run):
    return next(p.name[: -len("-samples.csv")] for p in run.glob("*-samples.csv"))


def settle_key(point):
    if point == "before-listen": return -1
    if point == "after-initial": return 0
    if point.startswith("after-update-"): return int(point.rsplit("-", 1)[1])
    return None


samples = defaultdict(list)  # (mode, phase, size, kind) -> rows
settled = defaultdict(list)  # (mode, phase, size, point) -> peer table entries
notes = []
for run in runs:
    mode = mode_of(run)
    # As on Android: each sample's baseline is the peer table at the last settle point before it, and updates straight
    # after a settle are kept apart (*update, after a settle*), since the previous snapshots' entries are gone then.
    run_settles = defaultdict(list)
    for row in csv.DictReader(open(run / f"{mode}-settled.csv")):
        key = settle_key(row["point"])
        if key is not None:
            run_settles[(row["phase"], int(row["size"]))].append((key, int(row["peers"])))
        if row["phase"] in ("query", "document"):
            settled[(mode, row["phase"], int(row["size"]), row["point"])].append(int(row["peers"]))
    for row in csv.DictReader(open(run / f"{mode}-samples.csv")):
        # Partial snapshots are skipped: older runs wrote them under phase "skipped", newer ones as kind "partial".
        if row["phase"] not in ("query", "document") or row["kind"] == "partial":
            continue
        seq, marks = int(row["seq"]), run_settles[(row["phase"], int(row["size"]))]
        earlier = [p for k, p in marks if k < seq or (seq == 0 and k == -1)]
        row["peers_over_settled"] = str(float(row["peers_peak"]) - earlier[-1]) if earlier else ""
        kind = row["kind"]
        if kind == "update" and any(k == seq - 1 for k, _ in marks):
            kind = "update, after a settle"
        samples[(mode, row["phase"], int(row["size"]), kind)].append(row)
    host = (run / "host.txt").read_text() if (run / "host.txt").exists() else ""
    loads = re.findall(r"load averages?: ([\d.]+)", host)
    text = (run / f"{mode}-run.txt").read_text()
    def note(key):
        found = re.search(rf"^{key}: (.*)$", text, re.M)
        return found.group(1) if found else "?"
    # The removal check is written as 'disposeRace' by current builds and was 'verifyRemoval' in earlier ones.
    removal = note('disposeRace')
    if removal == "?":
        removal = note('verifyRemoval')
    notes.append(f"| {run.name} | {mode} | {note('outcome')} | {' → '.join(loads) if loads else '?'} | "
                 f"{note('verify')} | {note('verifyPeerless')} | {removal} |")


def med(rows, key, scale=1.0):
    values = [float(r[key]) for r in rows if r.get(key)]
    return statistics.median(values) / scale if values else None


def cell(value, digits=1):
    return "–" if value is None else f"{value:,.{digits}f}"


present = [m for m in MODES if any(k[0] == m for k in samples)]
cases = sorted({k[1:] for k in samples}, key=lambda c: (c[0] != "query", c[1], {"initial": 0, "update": 1}.get(c[2], 2)))
both = "peered" in present and "peerless" in present

lines = ["# iOS: peered vs Peerless (generated)", "",
         f"Generated by `scripts/compare-ios.py` from {len(runs)} runs. Every cell is a median over all callbacks of "
         "that case in all runs of that mode. Wall and CPU span the whole path each mode has: peered from entry into the "
         ".NET listener; Peerless from entry into the Objective-C listener (so it includes encoding). Peered ends with "
         "the snapshot converted into plain .NET values, Peerless with it decoded into the Peerless model. As on Android, "
         "*update* rows leave out the updates straight after a settle point, which are listed as *update, after a "
         "settle*. Alloc in KiB.", "",
         "## Runs", "",
         "| run | mode | outcome | host load (1-min) before → after | read back as written | peered = Peerless | removal mutes |",
         "|---|---|---|---|---|---|---|", *notes, ""]


def times(ratio):
    # Whole numbers only from 10× up, so a narrow win or a loss (under 1×) isn't rounded to 1× or 0×.
    return f"{ratio:,.0f}×" if ratio >= 10 else f"{ratio:.1f}×" if ratio >= 1 else f"{ratio:.2f}×"


def table(title, key, scale, digits, explain):
    lines.extend([f"## {title}", "", explain, "",
                  "| docs | kind | " + " | ".join(present) + (" | peered ÷ peerless |" if both else " |"),
                  "|---:|---|" + "---:|" * len(present) + ("---:|" if both else "")])
    for phase, size, kind in cases:
        values = {m: med(samples.get((m, phase, size, kind), []), key, scale) for m in present}
        label = f"{size} (doc)" if phase == "document" else str(size)
        ratio = ""
        if both:
            p, d = values["peered"], values["peerless"]
            ratio = f" {times(p / d)} |" if p and d else " – |"
        lines.append(f"| {label} | {kind} | " + " | ".join(cell(values[m], digits) for m in present) + " |" + ratio)
    lines.append("")


table("Wall time per snapshot (ms)", "wall_us", 1000, 2, "Callback start to fully converted.")
table("Main-queue CPU per snapshot (ms)", "thread_cpu_us", 1000, 2,
      "Thread CPU time on the callback (main) thread over the same span; for Peerless this includes Objective-C encoding.")
table("Managed allocation per snapshot (KiB)", "alloc_bytes", 1024, 0,
      ".NET allocations on the callback thread. Objective-C allocations (snapshot.data's dictionaries, the frame buffer) aren't counted in either mode.")
table("NSObject peers created per snapshot", "peers_created", 1, 0,
      "Every peer the runtime registered during the callback (the peer table's insertion count).")
table("NSObject peer table at peak during a snapshot, absolute", "peers_peak", 1, 0,
      "The table's highest entry count during the callback (sampled per document in peered mode): what an app holds. "
      "Entries are native retains held; a GC can't remove one while the main-queue callback runs (NSObject_Disposer "
      "drains on the main queue). Peerless's figure is the app's own entries.")
table("NSObject peer table at peak, over the last settle", "peers_over_settled", 1, 0,
      "The absolute peak minus the table's count at the last settle point (always the app's own 7), as Android's GREF "
      "figure subtracts its settled count.")
table("GCs during a snapshot", "gen0", 1, 0, "Collections of any generation that started inside the callback.")

lines += ["## Settled peers (after forced GC, finalizers and a main-queue turn)", "",
          "The runtime's peer table at the settle points (median across runs).", "",
          "| docs | point | " + " | ".join(present) + " |", "|---:|---|" + "---:|" * len(present)]
for phase, size in sorted({(k[1], k[2]) for k in settled}, key=lambda c: (c[0] != "query", c[1])):
    for point in ("before-listen", "after-initial", "after-update-20", "after-update-48", "after-remove"):
        if not any(settled.get((m, phase, size, point)) for m in present):
            continue
        values = [settled.get((m, phase, size, point)) for m in present]
        lines.append(f"| {size}{' (doc)' if phase == 'document' else ''} | {point} | "
                     + " | ".join(f"{statistics.median(v):,.0f}" if v else "–" for v in values) + " |")
lines.append("")

if "peerless" in present:
    lines += ["## Peerless: where the time goes", "",
              "Medians. *Encode* is the Objective-C side alone, including Firestore's `snapshot.data` (shown separately). *ObjC→.NET* is Objective-C callback entry to .NET "
              "entry (encode and the call). *.NET* is .NET entry to fully decoded.", "",
              "| docs | kind | frame KiB | encode ms | encode CPU ms | of which snapshot.data ms | ObjC→.NET ms | .NET ms | end-to-end ms |",
              "|---:|---|---:|---:|---:|---:|---:|---:|---:|"]
    for phase, size, kind in cases:
        rows = samples.get(("peerless", phase, size, kind), [])
        if not rows:
            continue
        lines.append(f"| {size}{' (doc)' if phase == 'document' else ''} | {kind} | "
                     f"{cell(med(rows, 'frame_bytes', 1024))} | {cell(med(rows, 'native_encode_us', 1000), 2)} | "
                     f"{cell(med(rows, 'native_encode_cpu_us', 1000), 2)} | {cell(med(rows, 'native_data_us', 1000), 2)} | {cell(med(rows, 'native_to_dotnet_us', 1000), 2)} | "
                     f"{cell(med(rows, 'dotnet_us', 1000), 2)} | {cell(med(rows, 'wall_us', 1000), 2)} |")
    lines.append("")

out.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
